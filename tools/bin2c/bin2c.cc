//
// bin2c — embed a file into a program as a C++ constexpr array.
//
// Usage: bin2c <input_file> <output.hh> <variable_name> [namespace]
//
// Generates a header with:
//   constexpr std::array<std::uint8_t, N> <variable_name> = {{ ... }};
//   inline std::span<const std::uint8_t> <variable_name>_data() { ... }
//
// A build-time tool: neutrino_embed_files() (cmake/neutrino_embed.cmake) runs it, built for
// the host also when the program is cross-compiled (Emscripten). Taken from warlords'
// tools/buildtools/bin2c.cc. Standard library only, so the host compiler builds it alone.
//

#include <cstddef>
#include <cstdint>
#include <cstdio>
#include <fstream>
#include <iostream>
#include <string>
#include <vector>

int main(int argc, char* argv[]) {
    if (argc < 4 || argc > 5) {
        std::cerr << "Usage: bin2c <input> <output.hh> <variable> [namespace]\n";
        return 1;
    }

    const char* input_path = argv[1];
    const char* output_path = argv[2];
    const char* var_name = argv[3];
    const char* ns = (argc >= 5) ? argv[4] : nullptr;

    // Read input file
    std::ifstream in(input_path, std::ios::binary | std::ios::ate);
    if (!in) {
        std::cerr << "bin2c: cannot open input: " << input_path << "\n";
        return 1;
    }

    const auto size = static_cast<std::size_t>(in.tellg());
    in.seekg(0);
    std::vector<unsigned char> data(size);
    in.read(reinterpret_cast<char*>(data.data()), static_cast<std::streamsize>(size));
    if (!in) {
        std::cerr << "bin2c: read error: " << input_path << "\n";
        return 1;
    }
    in.close();

    // Generate output
    std::ofstream out(output_path);
    if (!out) {
        std::cerr << "bin2c: cannot create output: " << output_path << "\n";
        return 1;
    }

    out << "// Auto-generated by bin2c — do not edit.\n";
    out << "// Source: " << input_path << "\n\n";
    out << "#pragma once\n\n";
    out << "#include <array>\n";
    out << "#include <cstdint>\n";
    out << "#include <span>\n\n";

    if (ns) {
        out << "namespace " << ns << " {\n\n";
    }

    out << "constexpr std::array<std::uint8_t, " << size << "> " << var_name << " = {{\n";

    for (std::size_t i = 0; i < size; ++i) {
        if (i % 16 == 0) {
            out << "    ";
        }
        out << "0x";
        const char hex[] = "0123456789ABCDEF";
        out << hex[data[i] >> 4] << hex[data[i] & 0x0F];
        if (i + 1 < size) {
            out << ',';
        }
        if (i % 16 == 15 || i + 1 == size) {
            out << '\n';
        }
    }

    out << "}};\n\n";

    out << "inline std::span<const std::uint8_t> " << var_name << "_data() {\n";
    out << "    return " << var_name << ";\n";
    out << "}\n";

    if (ns) {
        out << "\n} // namespace " << ns << "\n";
    }

    // A full disk must not leave a truncated header that the build then takes as made.
    out.close();
    if (!out) {
        std::cerr << "bin2c: write error: " << output_path << "\n";
        std::remove(output_path);
        return 1;
    }

    return 0;
}
